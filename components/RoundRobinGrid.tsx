/**
 * The bracket for a tournament's computed views, and where its stats scope is
 * picked: every round heading carries a "Scope round" chip and every card a
 * "Game" chip, so the selector sits on the thing it selects rather than in a
 * popup above the tables. Checking a round autoselects every game in it —
 * the chips underneath light up with it — and unchecking a single game then
 * narrows the scope to the rest, so any combination (Round 5 Game 1 together
 * with Round 6 Game 1, say) is still reachable.
 *
 * Everything here is link-driven (plain navigations to `?rounds=` / `?games=`
 * URLs with `scroll={false}`, so changing the selection keeps your place in
 * the page), so the selection is bookmarkable and needs no client state of
 * its own.
 *
 * Scoped-down stats recompute server-side from the raw files (the raw ~2 MB
 * of JSON is never serialized into this client component), so the browser
 * only ever receives the scope definition plus the finished numbers — the
 * same precompute-and-serialize split the rest of this page uses.
 */
'use client';

import Link from 'next/link';
import { useMemo, useState } from 'react';
import {
  generateRoundRobin,
  scopeQuery,
  type BracketFileSummary,
  type StatsScope,
} from '@/lib/schedule';
import BracketTeamRow from '@/components/BracketTeamRow';
import type { BracketMatchup } from '@/lib/schedule';
import type { Team } from '@/lib/types';

/**
 * Autogenerated round-robin bracket, Challonge-style: every round is a
 * heading on its own line containing compact matchup cards. Rounds are
 * numbered sequentially — Round 1..6 for a double round robin (the rematch
 * leg keeps its own number, so no round repeats and no "(reverse)" tags are
 * needed), Round 1..5 for a single one — as generated by generateRoundRobin.
 * Each card lists both teams (as their full, equally-emphasized roster — no
 * leader-vs-members hierarchy) and their scores, winner highlighted. A
 * `win` / `tie` tag sits inline next to the team it applies to rather
 * than on its own line; unplayed fixtures show dashes so a freshly created
 * tournament still renders the full fixture list. Fixtures are derived
 * purely from the team list.
 *
 * Which uploaded file belongs to which fixture is worked out by the caller
 * (see summarizeBracketFiles + matchFilesToBracket in lib/schedule.ts) and
 * arrives here as `files`, keyed by slot. This component is a client
 * component, so anything passed in is serialized into the page response —
 * which is why it receives only each file's label and scores rather than the
 * raw JSON exports behind them. Hovering a team's cell highlights every cell
 * that team plays in — in every round — so one squad's whole set of games can
 * be read straight off the bracket; that hovered-team id lives here rather
 * than inside a card, because the cells it lights up are spread across all
 * the round sections below.
 */
export default function RoundRobinGrid({
  teams,
  files,
  scope,
  matchPath,
}: {
  teams: Team[];
  files: Record<string, BracketFileSummary>;
  // The stats scope as picked in the round and game chips; null hides both
  // entirely (the admin form's bracket, which picks files, not stats slices).
  // Chips link to `matchPath` with the sliced query string, so picking one is
  // a plain navigation — no client state to keep in sync with the tables.
  scope: StatsScope | null;
  matchPath?: string;
}) {
  const rounds = generateRoundRobin(teams);

  // Team index whose cells are highlighted right now, or null when the pointer
  // is off the bracket entirely. Cleared on the wrapper's mouseleave rather than
  // each cell's, so sliding from one cell to the next — including between two
  // cells of the same team — never blinks the highlight off in between.
  const [hoveredTeam, setHoveredTeam] = useState<number | null>(null);

  // Rounds with at least one attached file. Scoping to a round with nothing in
  // it would slice the tables down to nothing, which is never what the chip
  // means, so those render disabled — the rule the Scope popup used to apply.
  const playableRounds = useMemo(() => {
    const withFiles = new Set<number>();
    for (const round of rounds) {
      if (round.matchups.some((m) => files[m.slot])) withFiles.add(round.displayRound);
    }
    return withFiles;
  }, [rounds, files]);

  // The games currently in scope. A checked round autoselects every game in
  // it, so its cards light up together with the round instead of going dead —
  // which is what makes "check the round, then drop the one game I don't
  // want" a two-click operation.
  const activeGames = useMemo(() => {
    const active = new Set<string>();
    if (!scope) return active;
    for (const round of rounds) {
      if (scope.rounds.includes(round.displayRound)) {
        for (const m of round.matchups) active.add(m.slot);
      }
    }
    for (const slot of scope.games) active.add(slot);
    return active;
  }, [scope, rounds]);

  if (rounds.length === 0) return null;

  // Every control is a plain link to the scope it produces, so the selection
  // stays bookmarkable and needs no client state of its own.
  function hrefFor(next: StatsScope): string {
    return `${matchPath ?? ''}${scopeQuery(next)}`;
  }

  function gameHref(slot: string): string {
    if (!scope) return matchPath ?? '';
    if (activeGames.has(slot)) {
      // Dropping a game out of a checked round can't stay a round selection,
      // so the scope becomes the explicit list of the games still in it;
      // dropping the last one falls back to all stats.
      return hrefFor({ rounds: [], games: [...activeGames].filter((s) => s !== slot) });
    }
    return hrefFor({ rounds: [], games: [...scope.games, slot] });
  }

  // Checking a round takes its games along, so any game picks are dropped —
  // and come back if the last checked round is unchecked again. Rounds and
  // game picks never mix (see scopeQuery).
  function roundHref(displayRound: number): string {
    if (!scope) return matchPath ?? '';
    const next = scope.rounds.includes(displayRound)
      ? scope.rounds.filter((r) => r !== displayRound)
      : [...scope.rounds, displayRound].sort((a, b) => a - b);
    return hrefFor({ rounds: next, games: next.length > 0 ? [] : scope.games });
  }

  return (
    <div className="space-y-3" onMouseLeave={() => setHoveredTeam(null)}>
      {rounds.map((round) => {
        const roundSelected = scope !== null && scope.rounds.includes(round.displayRound);
        const playable = playableRounds.has(round.displayRound);
        return (
          <div key={round.displayRound}>
            <div className="mb-1 flex flex-wrap items-center justify-between gap-2">
              <h3 className="text-xs font-semibold uppercase tracking-wide text-textMuted">
                Round {round.displayRound}
              </h3>
              {/* Round-level scope, sitting on the round it scopes — the
                  tables below are sliced by whatever is lit here. */}
              {scope !== null && matchPath && (
                <Link
                  href={roundHref(round.displayRound)}
                  scroll={false}
                  aria-disabled={!playable}
                  title={
                    !playable
                      ? 'No games attached in this round yet'
                      : roundSelected
                        ? 'Remove this round from the stats scope'
                        : 'Scope the stats tables to this round'
                  }
                  className={`rounded-full px-2 py-0.5 text-[0.6rem] font-medium transition-colors ${
                    !playable
                      ? 'pointer-events-none border border-border text-textDim opacity-50'
                      : roundSelected
                        ? 'bg-accent text-bg'
                        : 'border border-border text-textMuted hover:border-textSub hover:text-text'
                  }`}
                >
                  {roundSelected ? '✓ Selected' : 'Select Round'}
                </Link>
              )}
            </div>
            <div className="grid grid-cols-1 gap-1.5 sm:grid-cols-2">
              {round.matchups.map((m, i) => (
                <MatchupCard
                  key={m.slot}
                  matchup={m}
                  gameNumber={i + 1}
                  teamA={teams[m.teamAIndex]}
                  teamB={teams[m.teamBIndex]}
                  file={files[m.slot]}
                  hoveredTeam={hoveredTeam}
                  onHoverTeam={setHoveredTeam}
                  gameSelected={scope !== null && activeGames.has(m.slot)}
                  gameTitle={
                    scope !== null && activeGames.has(m.slot)
                      ? 'Remove this game from the stats scope'
                      : 'Add this game to the stats scope'
                  }
                  gameDisabled={scope === null || !matchPath}
                  gameHref={gameHref(m.slot)}
                />
              ))}
            </div>
          </div>
        );
      })}
    </div>
  );
}

function MatchupCard({
  matchup,
  gameNumber,
  teamA,
  teamB,
  file,
  hoveredTeam,
  onHoverTeam,
  gameSelected,
  gameTitle,
  gameDisabled,
  gameHref,
}: {
  matchup: BracketMatchup;
  gameNumber: number;
  teamA: Team;
  teamB: Team;
  file?: BracketFileSummary;
  hoveredTeam: number | null;
  onHoverTeam: (teamIndex: number) => void;
  // Game-level stats-scope chip: links to the sliced URL when enabled.
  // Missing entirely on read-only bracket renders — the admin form drives
  // its own attach-file flow through these cards, not a stats scope. A
  // disabled chip means the game is already kept by its checked round, so
  // linking anywhere would change nothing.
  gameSelected?: boolean;
  // Hover title for the chip: adding to an existing game selection is worded
  // differently from scoping to a first one.
  gameTitle?: string;
  gameDisabled?: boolean;
  gameHref?: string;
}) {
  const scores = file?.scores;
  const aScore = scores?.[matchup.labelA.toLowerCase().trim()];
  const bScore = scores?.[matchup.labelB.toLowerCase().trim()];
  const bothScored = aScore !== undefined && bScore !== undefined;
  const aWin = bothScored && aScore > bScore;
  const bWin = bothScored && bScore > aScore;
  const tie = bothScored && aScore === bScore;

  return (
    <div
      className={`rounded-md border px-2 py-1 ${
        bothScored ? 'border-border bg-surface' : 'border-dashed border-border bg-surface/40'
      }`}
    >
      <div className="flex items-center justify-between gap-2">
        <span className="text-[0.6rem] uppercase tracking-wide text-textDim">
          Round {matchup.displayRound} · Game {gameNumber}
        </span>
        {gameHref && !gameDisabled && (
          <Link
            href={gameHref}
            scroll={false}
            title={
              gameTitle ??
              (gameSelected ? 'Remove this game from the stats scope' : 'Scope stats to this game')
            }
            className={`rounded-full px-2 py-0.5 text-[0.6rem] font-medium transition-colors ${
              gameSelected
                ? 'bg-accent text-bg'
                : 'border border-border text-textMuted hover:border-textSub hover:text-text'
            }`}
          >
            {gameSelected ? '✓ Game' : 'Game'}
          </Link>
        )}
      </div>
      <Row
        members={teamA}
        teamIndex={matchup.teamAIndex}
        score={aScore}
        result={tie ? 'tie' : aWin ? 'win' : null}
        highlighted={hoveredTeam === matchup.teamAIndex}
        onHover={onHoverTeam}
      />
      <Row
        members={teamB}
        teamIndex={matchup.teamBIndex}
        score={bScore}
        result={tie ? 'tie' : bWin ? 'win' : null}
        highlighted={hoveredTeam === matchup.teamBIndex}
        onHover={onHoverTeam}
      />
    </div>
  );
}

// One team of a matchup, rendered through the shared bracket row (see
// components/BracketTeamRow.tsx — same roster chips, team colors, hover
// highlight and win/tie tag as the admin form's bracket) with this view's
// read-only score pill passed in as the right-hand control.
function Row({
  members,
  teamIndex,
  score,
  result,
  highlighted,
  onHover,
}: {
  members: Team;
  teamIndex: number;
  score?: number;
  result: 'win' | 'tie' | null;
  highlighted: boolean;
  onHover: (teamIndex: number) => void;
}) {
  const win = result === 'win';
  const tie = result === 'tie';
  return (
    <BracketTeamRow
      members={members}
      teamIndex={teamIndex}
      result={result}
      highlighted={highlighted}
      onHover={onHover}
      score={
        <span
          className={`flex-shrink-0 rounded px-1.5 text-xs font-semibold ${
            win
              ? 'bg-accent text-bg'
              : tie
                ? 'bg-surfaceAlt text-text'
                : score === undefined
                  ? 'text-textDim'
                  : 'text-textMuted'
          }`}
        >
          {score === undefined ? '–' : score}
        </span>
      }
    />
  );
}