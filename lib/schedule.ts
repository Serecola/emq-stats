// ---- autogenerated bracket -------------------------------------------------

export interface BracketMatchup {
  slot: string; // opaque stable key, e.g. "r1m0" = fixture, match 0. The
  //              number is the fixture's position in the legacy
  //              cycle-major sequence (round robin) or its round number
  //              (3v3v3) — see generateBracket. Never derive it from
  //              display order: it is persisted on saved files.
  displayRound: number; // 1-based sequential round shown on screen — Round
  //              1..6 for a double round robin, Round 1..5 for a single one,
  //              Round 1..5 for a 3v3v3 tournament.
  //              Unlike `round` it never repeats, so it is what round
  //              headings, file labels and the stats scope use.
  round: number; // 1-based round within a single round-robin pass. The
  //                reverse leg repeats the same numbers, so displayRound
  //                2 is round 1's rematch, 4 is round 2's, 6 is round 3's.
  //                A 3v3v3 tournament has a single leg, so round is simply
  //                the display round.
  cycle: number; // 1-based round-robin cycle this round belongs to — always
  //                1 for a 3v3v3 tournament (there are no cycles).
  /**
   * Every team playing this fixture, in display order: two indices for a
   * round-robin pairing, all three for a 3v3v3 round. Together with `labels`
   * this is a fixture's whole team list — nothing should assume a fixture
   * has exactly two teams.
   */
  teamIndices: number[];
  /** `teamIndices.map((i) => teams[i][0])` — each participating team's label. */
  labels: string[];
}

export interface BracketRound {
  displayRound: number; // sequential round number shown on screen (1..6)
  round: number; // round number within its cycle (repeats on the reverse leg)
  cycle: number; // 1-based cycle this leg belongs to, so round + cycle is unique
  matchups: BracketMatchup[];
}

export function bracketSlot(round: number, index: number): string {
  return `r${round}m${index}`;
}

/**
 * One single round-robin pass using the circle method: team 0 is pinned
 * and the rest rotate, producing `n - 1` rounds of `n / 2` pairings.
 * Returns raw index pairs per round.
 */
function singleRoundRobinPairs(n: number): [number, number][][] {
  const rot: number[] = [];
  for (let i = 1; i < n; i++) rot.push(i);
  const rounds: [number, number][][] = [];
  for (let r = 0; r < n - 1; r++) {
    const pairs: [number, number][] = [[0, rot[rot.length - 1]]];
    for (let k = 0; k < (n - 2) / 2; k++) {
      pairs.push([rot[k], rot[rot.length - 2 - k]]);
    }
    rounds.push(pairs);
    rot.unshift(rot.pop() as number); // rotate clockwise
  }
  return rounds;
}

/**
 * Builds the full fixture bracket for a tournament: every round with its
 * matchups, autogenerated from the team list. The shape follows the team
 * count (see lib/format.ts):
 *
 *  - 4 teams — a double round robin (2 cycles, 6 legs)
 *  - 6 teams — a single round robin (5 rounds)
 *  - 3 teams — no round robin: five rounds of 3v3v3, each round one game
 *    with all three teams in it (the 9-player format, three teams of three)
 *
 * For a round robin, the second cycle repeats each pairing in the same
 * order — a rematch lists the two teams exactly as the leg it mirrors did,
 * rather than flipping which side each team is on — and each of its legs is
 * emitted directly after the round it mirrors: R1, R1 (rematch), R2, R2
 * (rematch), ... rather than appending the whole second cycle at the end,
 * so a round and its rematch read as one block.
 *
 * Every matchup carries a stable `slot` key so an uploaded JSON file (and
 * its scores) can be attached to a specific fixture. Round-robin slots keep
 * the cycle-major numbering they have always had (cycle * roundsPerCycle +
 * round); a 3v3v3 round is r<round>m0. Both are persisted on saved files,
 * so they must not be renumbered to follow the display order above.
 */
export function generateBracket(teams: Team[]): BracketRound[] {
  const n = teams.length;
  if (!isValidTeamCount(n)) return [];

  // 3v3v3: five rounds, one game each, every team in every game. No
  // pairings, no cycles, no legs — each round is its own display round.
  if (isThreeWayFormat(n)) {
    const labels = teams.map((team) => team[0]);
    return Array.from({ length: THREE_WAY_ROUNDS }, (_, i) => {
      const displayRound = i + 1;
      const matchup: BracketMatchup = {
        slot: bracketSlot(displayRound, 0),
        displayRound,
        round: displayRound,
        cycle: 1,
        teamIndices: teams.map((_, teamIndex) => teamIndex),
        labels,
      };
      return { displayRound, round: displayRound, cycle: 1, matchups: [matchup] };
    });
  }

  const cycles = roundRobinCycles(n);
  const base = singleRoundRobinPairs(n);
  const roundsPerCycle = base.length;
  const rounds: BracketRound[] = [];
  let displayRound = 0;
  for (let r = 0; r < roundsPerCycle; r++) {
    for (let c = 0; c < cycles; c++) {
      displayRound++;
      const matchups: BracketMatchup[] = base[r].map(([a, b], i) => {
        // Second cycle keeps the pairing's own order: the rematch reads the
        // same way as the leg it mirrors (same team listed first), instead of
        // swapping which side each team is on.
        return {
          slot: bracketSlot(c * roundsPerCycle + r + 1, i),
          displayRound,
          round: r + 1,
          cycle: c + 1,
          teamIndices: [a, b],
          labels: [teams[a][0], teams[b][0]],
        };
      });
      rounds.push({ displayRound, round: r + 1, cycle: c + 1, matchups });
    }
  }
  return rounds;
}

/**
 * Roster team indices whose players appear in a raw song-history file —
 * counting a substitute as presence on the team of the player they stood in
 * for, so an export with a sub in it still resolves to its teams (and thus
 * its fixture) instead of falling out of the bracket as unplaceable.
 */
export function fileParticipantIndices(
  file: Pick<MatchFile, 'data'>,
  teams: Team[],
  renames: Record<string, string> = {},
  substitutes: Record<string, string> = {}
): number[] {
  const present = fileRosterMembers(file, teams, renames);
  const idx: number[] = [];
  teams.forEach((team, i) => {
    if (team.some((name) => present.has(norm(name)))) idx.push(i);
  });
  // A team none of whose roster members appear can still have played the
  // game through a sub — check the room's other names against the substitute
  // map. Both lookups (raw and renamed) are tried: a sub is never *also*
  // renamed, but the export's name may have been reconciled as one or the
  // other since, and either answer must still fill the slot.
  if (idx.length < teams.length && Object.keys(substitutes).length > 0) {
    const normTeams = teams.map((t) => t.map(norm));
    for (const raw of extractUsernames(file.data)) {
      const key = norm(renames[norm(raw)] || raw);
      const target = substitutes[norm(raw)] ?? substitutes[key];
      if (!target) continue;
      const ti = normTeams.findIndex((t) => t.includes(norm(target)));
      if (ti !== -1 && !idx.includes(ti)) idx.push(ti);
    }
    idx.sort((a, b) => a - b);
  }
  return idx;
}

/**
 * The play timestamp the game writes into its own export name —
 * `EMQ_SongHistory_2026-09-27T01_52_55` → `2026-09-27T01_52_55`. Every
 * component is fixed width, so comparing the strings is already a
 * chronological comparison. Files renamed to something without one
 * (or hand-labelled at save time) get null.
 */
export function exportTimestamp(label: string): string | null {
  const m = label.match(/\d{4}-\d{2}-\d{2}T\d{2}[_:]\d{2}[_:]\d{2}/);
  return m ? m[0] : null;
}

/**
 * The export's own name as it should be *shown*, without the prefix the game
 * writes into every one of them: `EMQ_SongHistory_2026-09-27T01_52_55` →
 * `2026-09-27T01_52_55`.
 *
 * Display only. The stored label keeps the prefix, because that name is the
 * file's real identity: a download hands it back under exactly that name, and
 * the bracket reads a pair's two legs' play time out of it (see
 * exportTimestamp). The prefix is identical on every upload, so it says
 * nothing the viewer doesn't already know, and all it does is push the
 * timestamp that *does* differ off the end of a truncated filename. Names
 * without it (a hand-saved file, say) and empty labels come back untouched.
 */
export function exportDisplayLabel(label: string): string {
  return label.replace(/^EMQ_SongHistory_/i, '');
}

/**
 * Fingerprints one export's raw JSON so two uploads can be compared for
 * identity. Key order and whitespace are normalized away (object keys sorted,
 * arrays left in order — the song history's order is the game's own), so an
 * export re-uploaded later, or one that came back out of the database
 * pretty-printed by the admin form, compares equal to the copy already
 * attached. A plain text compare would not: the form seeds saved files with
 * `JSON.stringify(data, null, 2)` while a fresh upload keeps the game's own
 * formatting, so the very re-upload this exists to catch would look different
 * on every upload path but the original.
 *
 * Used only for exact duplicates — one export is one game, so an identical
 * file attached twice is always the same game counted twice. Genuinely
 * different games differ in content (every song entry carries its own
 * `PlayedAt`), so there is no collision to confuse it with.
 */
export function fileContentSignature(data: unknown): string {
  return canonicalJson(data);
}

function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== 'object') {
    // `undefined` reaches here for an absent property; JSON has no such thing,
    // so it's spelled the same way `JSON.stringify` would leave it out.
    return JSON.stringify(value) ?? 'null';
  }
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`).join(',')}}`;
}

/**
 * Orders two exports by the time in their names, earliest first. This is the
 * order pass 2 of matchFilesToBracket tries them in, so when a pair has two
 * recorded games the earlier one lands on the pair's first fixture and the
 * later one on its rematch. Files with no parseable timestamp sort after the
 * timed ones and keep their relative order (sort is stable).
 */
function compareByExportTime(a: string, b: string): number {
  const ta = exportTimestamp(a);
  const tb = exportTimestamp(b);
  if (ta === null && tb === null) return 0;
  if (ta === null) return 1;
  if (tb === null) return -1;
  return ta < tb ? -1 : ta > tb ? 1 : 0;
}

/**
 * A fixture's identity for file placement: its teams sorted, so the key is
 * the same whichever side a pairing lists first — "0,3" for a round-robin
 * pairing (the pair key this has always used), "0,1,2" for a 3v3v3 round,
 * where all five rounds share one key and fill in bracket order.
 */
function teamSetKey(indices: number[]): string {
  return [...indices].sort((a, b) => a - b).join(',');
}

export interface BracketAssignment {
  bySlot: Record<string, MatchFile>; // matchup slot -> attached file
  unmatched: MatchFile[]; // files that couldn't be tied to a fixture
}

/**
 * Binds uploaded files to bracket matchups. Files carrying an explicit
 * `slot` win outright; the rest are matched by the exact set of teams
 * detected in them (first empty fixture for that set, tried in export-time
 * order so an earlier game lands on its first fixture — see
 * compareByExportTime). Anything left over is returned as `unmatched` so it
 * isn't silently dropped.
 */
export function matchFilesToBracket(
  teams: Team[],
  files: MatchFile[],
  renames: Record<string, string> = {},
  substitutes: Record<string, string> = {}
): BracketAssignment {
  const rounds = generateBracket(teams);
  // Fixture key -> slots in bracket order. The key is the sorted set of the
  // fixture's teams, covering both shapes: a round-robin pairing behaves
  // exactly as the pair key always has (one key under two legs of a double
  // round robin), while every 3v3v3 round shares the "0,1,2" key and so
  // fills in bracket order the same way a pair's two legs do.
  const slotsByTeams = new Map<string, string[]>();
  const allSlots: string[] = [];
  for (const rr of rounds) {
    for (const m of rr.matchups) {
      const key = teamSetKey(m.teamIndices);
      (slotsByTeams.get(key) ?? slotsByTeams.set(key, []).get(key)!).push(m.slot);
      allSlots.push(m.slot);
    }
  }

  const bySlot: Record<string, MatchFile> = {};
  const used = new Set<string>();
  const remaining: MatchFile[] = [];

  // Pass 1: explicit slots.
  for (const file of files) {
    if (file.slot && allSlots.includes(file.slot) && !bySlot[file.slot]) {
      bySlot[file.slot] = file;
      used.add(file.id);
    } else {
      remaining.push(file);
    }
  }

  // Pass 2: infer by the teams present in each file. A fixture set that
  // recurs (a double round robin's pairing, a 3v3v3 tournament's identical
  // rounds) yields the same key in every such file, so the try order decides
  // which fixture each lands on: sort by the play time the game writes into
  // the export's own name (EMQ_SongHistory_2026-09-27T01_52_55) — the
  // earlier game first, so it fills the first free fixture and the later
  // one the next.
  for (const file of [...remaining].sort((a, b) => compareByExportTime(a.label, b.label))) {
    const idx = fileParticipantIndices(file, teams, renames, substitutes);
    if (idx.length < 2) continue;
    const slot = (slotsByTeams.get(teamSetKey(idx)) ?? []).find((s) => !bySlot[s]);
    if (slot) {
      bySlot[slot] = file;
      used.add(file.id);
    }
  }

  return { bySlot, unmatched: files.filter((f) => !used.has(f.id)) };
}

/**
 * The roster team indices a file's fixture is between, or null when it can't
 * be pinned to one: its `slot` (the form writes one for every fixture) wins
 * outright, otherwise the teams whose players appear in its raw JSON — the
 * same resolution matchFilesToBracket places uploads by. Without a slot the
 * detection has to be unambiguous: exactly two teams for a round-robin
 * pairing, all three for a 3v3v3 round (where every team plays every game).
 */
function fixtureTeamsFor(
  file: MatchFile,
  teams: Team[],
  renames: Record<string, string>,
  teamsBySlot: Map<string, number[]>,
  substitutes: Record<string, string> = {}
): number[] | null {
  if (file.slot) {
    const fixtureTeams = teamsBySlot.get(file.slot);
    if (fixtureTeams) return fixtureTeams;
  }
  const idx = fileParticipantIndices(file, teams, renames, substitutes);
  const expected = isThreeWayFormat(teams.length) ? teams.length : 2;
  return idx.length === expected ? idx : null;
}

/**
 * Completes the games the admin scored on one side only.
 *
 * An empty score box means that team scored nothing — not that the game went
 * unplayed — so a 12 typed against one team is a 12–0 win: it decides its
 * fixture, counts in the standings and earns points, instead of being dropped
 * as a file with "not enough scored teams", which is how reading the scores
 * literally treats it (and why a single-sided game used to show up nowhere).
 *
 * Every unscored team of the game's own fixture is completed (see
 * fixtureTeamsFor), so only the teams that actually played are credited with
 * a 0 — never every other team in the tournament. For a round-robin pairing
 * that is exactly the "one side blank" rule above; a 3v3v3 round typed into
 * one or two of its three boxes fills the rest the same way. A file that
 * can't be pinned to one fixture, or that has no scores at all, is left
 * exactly as saved: nothing is invented for a game nobody scored.
 *
 * Applied as matches are read (see lib/store.ts's rowToMatch) rather than as
 * they're saved, so a tournament that already carries a single-sided game —
 * and any written before this rule existed — behaves the same as a freshly
 * saved one, with no migration and no re-save. Idempotent: a filled-in 0 is
 * just a score like any other. The admin form applies the same assumption
 * at its two touch-points — it renders a blank opponent as 0 to decide a
 * fixture's result as a score is typed, and writes that 0 at submit (see
 * components/MatchForm.tsx) — so this remains the read-side guarantee for
 * anything saved without one.
 */
export function withAssumedZeroScores(
  teams: Team[],
  files: MatchFile[],
  renames: Record<string, string> = {},
  substitutes: Record<string, string> = {}
): MatchFile[] {
  const teamsBySlot = new Map<string, number[]>();
  for (const round of generateBracket(teams)) {
    for (const matchup of round.matchups) {
      teamsBySlot.set(matchup.slot, matchup.teamIndices);
    }
  }

  return files.map((file) => {
    const scores = file.scores;
    if (!scores || Object.keys(scores).length === 0) return file;
    const fixtureTeams = fixtureTeamsFor(file, teams, renames, teamsBySlot, substitutes);
    if (!fixtureTeams) return file;
    const blank = fixtureTeams.filter(
      (teamIndex) => scores[norm(teams[teamIndex][0])] === undefined
    );
    // Nothing entered against this fixture — which also covers the "score
    // belongs to none of these teams" case (a file attached to the wrong
    // slot by hand) — or nothing left to fill. Otherwise every blank side is
    // 0: for a pair, blank.length is 0 or 1 exactly as before; a 3v3v3 round
    // with one or two boxes typed fills the rest the same way.
    if (blank.length === 0 || blank.length === fixtureTeams.length) return file;
    const filled = { ...scores };
    for (const teamIndex of blank) filled[norm(teams[teamIndex][0])] = 0;
    return { ...file, scores: filled };
  });
}

/**
 * What a bracket card actually renders out of an attached file: which teams
 * scored what. `data` (the raw EMQ export, ~100 kB each) is
 * deliberately left behind.
 *
 * RoundRobinGrid is a client component, so anything handed to it is
 * serialized into the page response as well as the props — passing whole
 * files would ship every tournament's raw JSON to the browser, which is
 * what this shape exists to avoid. Slots with no attached file are simply
 * absent, and cards for them render as unplayed.
 */
export interface StatsScope {
  // Which displayed rounds are in scope (1-based `displayRound`). Empty =
  // every round.
  rounds: number[];
  // Individually-checked games, as bracket `slot` keys, on top of whatever
  // `rounds` covers. Empty = no single-game picks.
  games: string[];
}

/** True when the scope keeps nothing out — the whole tournament's stats. */
export function isFullScope(scope: StatsScope): boolean {
  return scope.rounds.length === 0 && scope.games.length === 0;
}

/**
 * The query string a scope is addressed by: rounds as `?rounds=3,4,6`, games
 * as a comma list of slots like `?games=r5m0,r6m0`, and nothing at all for
 * the full scope. Rounds and games never mix in one URL — a round selection
 * wins — so there is no case where both need serializing.
 */
export function scopeQuery(scope: StatsScope): string {
  const params = new URLSearchParams();
  if (scope.rounds.length > 0) params.set('rounds', scope.rounds.join(','));
  else if (scope.games.length > 0) params.set('games', scope.games.join(','));
  const query = params.toString();
  return query ? `?${query}` : '';
}

/**
 * Which of `match.files` fall inside `scope`, in the match's own file order.
 * Files are resolved to bracket fixtures exactly the way the bracket (and the
 * admin form) attaches them — explicit `slot` first, otherwise the two teams
 * detected in the file — so the stats slice agrees with the fixtures the
 * selector's round/game chips were built from. Files that can't be placed on
 * the bracket only count inside the full scope.
 */
export function filesInStatsScope(
  teams: Team[],
  files: MatchFile[],
  renames: Record<string, string>,
  scope: StatsScope,
  substitutes: Record<string, string> = {}
): MatchFile[] {
  if (isFullScope(scope)) return files;
  const assignment = matchFilesToBracket(teams, files, renames, substitutes);
  const slotToRound = new Map<string, number>();
  for (const matchups of generateBracket(teams).map((r) => r.matchups)) {
    for (const m of matchups) slotToRound.set(m.slot, m.displayRound);
  }
  const roundSet = new Set(scope.rounds);
  const gameSet = new Set(scope.games);
  const kept: MatchFile[] = [];
  for (const file of files) {
    const entry = Object.entries(assignment.bySlot).find(([, f]) => f.id === file.id);
    if (!entry) continue; // unmatched files have no round/game — full scope only
    const [slot] = entry;
    if (gameSet.has(slot)) {
      kept.push(file);
      continue;
    }
    const displayRound = slotToRound.get(slot);
    if (displayRound !== undefined && roundSet.has(displayRound)) kept.push(file);
  }
  return kept;
}

export interface BracketFileSummary {
  label: string;
  scores?: Record<string, number>;
}

export function summarizeBracketFiles(
  assignment: BracketAssignment
): Record<string, BracketFileSummary> {
  const summarized: Record<string, BracketFileSummary> = {};
  for (const [slot, file] of Object.entries(assignment.bySlot)) {
    summarized[slot] = { label: file.label, scores: file.scores };
  }
  return summarized;
}
