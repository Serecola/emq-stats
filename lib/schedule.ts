import { computeGameResult } from './results';
import { extractUsernames, fileRosterMembers, norm } from './stats';
import { isThreeWayFormat, isValidTeamCount, THREE_WAY_ROUNDS } from './format';
import type { Match, MatchFile, Team } from './types';

// The schedule shape is derived from the team count, never chosen separately
// — see lib/format.ts for the legal counts and what each one means. 4 teams
// always double round robin (every pair plays twice, 6 games per team), 6
// teams always single round robin (every pair plays once, 5 games per team),
// and 3 teams is not a round robin at all: five rounds of 3v3v3, every team
// in every round.

export function roundRobinCycles(teamCount: number): number {
  if (teamCount === 4) return 2;
  if (teamCount === 6) return 1;
  // 3-team tournaments aren't round robins — every caller branches on
  // isThreeWayFormat before asking. Anything else shouldn't happen if the
  // count constraint is enforced at save time; fall back to single round
  // robin rather than throwing mid-render.
  return 1;
}

export function gamesPerTeam(teamCount: number): number {
  // Every team plays every 3v3v3 round: five games, no pairings.
  if (isThreeWayFormat(teamCount)) return THREE_WAY_ROUNDS;
  return (teamCount - 1) * roundRobinCycles(teamCount);
}

export function totalGamesExpected(teamCount: number): number {
  // A 3v3v3 round is ONE game with all three teams in it, so five rounds
  // are five games — not the 3 * 5 / 2 a pair count would imply.
  if (isThreeWayFormat(teamCount)) return THREE_WAY_ROUNDS;
  return (teamCount * gamesPerTeam(teamCount)) / 2;
}

export interface FixturePairProgress {
  teamAIndex: number;
  teamBIndex: number;
  labelA: string;
  labelB: string;
  needed: number; // = cycles
  played: number; // games actually recorded between this exact pair
  remaining: number;
}

export interface ScheduleProgress {
  cycles: number;
  gamesPerTeam: number;
  totalExpected: number;
  totalRecorded: number;
  pairs: FixturePairProgress[];
  missingPairs: FixturePairProgress[]; // pairs with remaining > 0
  complete: boolean;
}

/**
 * Cross-references the expected fixture list against however many games are
 * actually recorded for each pair, so the admin can see what's left to
 * upload. Doesn't care which specific two games satisfy a 2x pairing — just
 * the count. A 3-team tournament has no pairs at all (its five 3v3v3 rounds
 * are each one game with every team in it), so its progress is simply how
 * many of the five are recorded.
 */
export function computeScheduleProgress(match: Pick<Match, 'teams' | 'files'>): ScheduleProgress {
  const teams = match.teams;
  const n = teams.length;

  if (isThreeWayFormat(n)) {
    const totalExpected = totalGamesExpected(n);
    const totalRecorded = Math.min(
      match.files.filter((f) => computeGameResult(f, teams) !== null).length,
      totalExpected
    );
    return {
      cycles: 1,
      gamesPerTeam: gamesPerTeam(n),
      totalExpected,
      totalRecorded,
      pairs: [],
      missingPairs: [],
      complete: totalRecorded >= totalExpected,
    };
  }

  const cycles = roundRobinCycles(n);

  // Count recorded games per pair by scanning every scored file.
  const playedCount = new Map<string, number>();
  for (const file of match.files) {
    const result = computeGameResult(file, teams);
    if (!result || result.entries.length !== 2) continue;
    const [i, j] = result.entries.map((e) => e.teamIndex).sort((a, b) => a - b);
    const key = `${i},${j}`;
    playedCount.set(key, (playedCount.get(key) ?? 0) + 1);
  }

  const pairs: FixturePairProgress[] = [];
  for (let i = 0; i < n; i++) {
    for (let j = i + 1; j < n; j++) {
      const played = playedCount.get(`${i},${j}`) ?? 0;
      pairs.push({
        teamAIndex: i,
        teamBIndex: j,
        labelA: teams[i][0],
        labelB: teams[j][0],
        needed: cycles,
        played,
        remaining: Math.max(0, cycles - played),
      });
    }
  }

  const totalRecorded = pairs.reduce((s, p) => s + Math.min(p.played, p.needed), 0);
  const totalExpected = totalGamesExpected(n);

  return {
    cycles,
    gamesPerTeam: gamesPerTeam(n),
    totalExpected,
    totalRecorded,
    pairs,
    missingPairs: pairs.filter((p) => p.remaining > 0),
    complete: pairs.every((p) => p.remaining === 0),
  };
}

