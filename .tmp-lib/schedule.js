/**
 * One single round-robin pass using the circle method: team 0 is pinned
 * and the rest rotate, producing `n - 1` rounds of `n / 2` pairings.
 * Returns raw index pairs per round.
 */
function singleRoundRobinPairs(n) {
    const rot = [];
    for (let i = 1; i < n; i++)
        rot.push(i);
    const rounds = [];
    for (let r = 0; r < n - 1; r++) {
        const pairs = [[0, rot[rot.length - 1]]];
        for (let k = 0; k < (n - 2) / 2; k++) {
            pairs.push([rot[k], rot[rot.length - 2 - k]]);
        }
        rounds.push(pairs);
        rot.unshift(rot.pop()); // rotate clockwise
    }
    return rounds;
}
/**
 * Builds the full fixture bracket for a tournament: every round with its
 * matchups, autogenerated from the team list. 4 teams produce a double
 * round robin (2 cycles, 6 legs), 6 teams a single one (5 rounds). The
 * second cycle flips each pairing's side, and each of its legs is emitted
 * directly after the round it mirrors — R1, R1 (reverse), R2, R2
 * (reverse), ... — rather than appending the whole reversed cycle at the
 * end, so a round and its rematch read as one block.
 *
 * Every matchup carries a stable `slot` key so an uploaded JSON file (and
 * its scores) can be attached to a specific fixture. Slots keep the
 * cycle-major numbering they have always had (cycle * roundsPerCycle +
 * round); they are persisted on saved files, so they must not be
 * renumbered to follow the display order above.
 */
function generateRoundRobin(teams) {
    const n = teams.length;
    if (!isValidTeamCount(n))
        return [];
    const cycles = roundRobinCycles(n);
    const base = singleRoundRobinPairs(n);
    const roundsPerCycle = base.length;
    const rounds = [];
    for (let r = 0; r < roundsPerCycle; r++) {
        for (let c = 0; c < cycles; c++) {
            const matchups = base[r].map(([a, b], i) => {
                const [x, y] = c === 1 ? [b, a] : [a, b];
                return {
                    slot: bracketSlot(c * roundsPerCycle + r + 1, i),
                    round: r + 1,
                    cycle: c + 1,
                    teamAIndex: x,
                    teamBIndex: y,
                    labelA: teams[x][0],
                    labelB: teams[y][0],
                };
            });
            rounds.push({ round: r + 1, cycle: c + 1, matchups });
        }
    }
    return rounds;
}
