/**
 * Binds uploaded files to bracket matchups. Files carrying an explicit
 * `slot` win outright; the rest are matched by the two teams detected in
 * them (first empty slot for that pair). Anything left over is returned
 * as `unmatched` so it isn't silently dropped.
 */
function matchFilesToBracket(teams, files, renames = {}) {
    const rounds = generateRoundRobin(teams);
    // Pair key -> slots in bracket order (2 for a double round robin).
    const slotsByPair = new Map();
    const allSlots = [];
    for (const rr of rounds) {
        for (const m of rr.matchups) {
            const key = `${Math.min(m.teamAIndex, m.teamBIndex)},${Math.max(m.teamAIndex, m.teamBIndex)}`;
            (slotsByPair.get(key) ?? slotsByPair.set(key, []).get(key)).push(m.slot);
            allSlots.push(m.slot);
        }
    }
    const bySlot = {};
    const used = new Set();
    const remaining = [];
    // Pass 1: explicit slots.
    for (const file of files) {
        if (file.slot && allSlots.includes(file.slot) && !bySlot[file.slot]) {
            bySlot[file.slot] = file;
            used.add(file.id);
        }
        else {
            remaining.push(file);
        }
    }
    // Pass 2: infer by the two teams present in each file.
    for (const file of remaining) {
        const idx = fileParticipantIndices(file, teams, renames);
        if (idx.length !== 2)
            continue;
        const key = `${Math.min(idx[0], idx[1])},${Math.max(idx[0], idx[1])}`;
        const slot = (slotsByPair.get(key) ?? []).find((s) => !bySlot[s]);
        if (slot) {
            bySlot[slot] = file;
            used.add(file.id);
        }
    }
    return { bySlot, unmatched: files.filter((f) => !used.has(f.id)) };
}
